import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
const root = fileURLToPath(new URL('../', import.meta.url));
export async function bundleData() {
  const data = {};
  for (const name of ['glossary', 'chapters', 'questions', 'bridges']) {
    data[name] = JSON.parse(await readFile(root + `data/${name}.json`, 'utf8'));
  }
  return `/* Generated by npm run build. Edit data/*.json instead. */\nwindow.GEN_BIO_DATA=${JSON.stringify(data).replace(/</g, '\\u003c')};\n`;
}
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  await writeFile(root + 'assets/data.js', await bundleData());
  if (process.argv.includes('--standalone')) {
    let html = await readFile(root + 'index.html', 'utf8');
    const css = await readFile(root + 'assets/styles.css', 'utf8');
    const js = await readFile(root + 'assets/app.js', 'utf8');
    const awaitedData = await bundleData();
    const icon = await readFile(root + 'assets/icon.svg', 'utf8');
    html = html.replace('<link rel="stylesheet" href="assets/styles.css">', () => `<style>${css}</style>`)
      .replace('href="assets/icon.svg"', () => `href="data:image/svg+xml,${encodeURIComponent(icon)}"`)
      .replace('<script src="assets/data.js" defer></script>', () => `<script>${awaitedData}</script>`)
      .replace('<script src="assets/app.js" defer></script>', () => `<script>${js.replace(/<\/script/gi, '<\\/script')}</script>`);
    await mkdir(root + 'dist', { recursive: true });
    await writeFile(root + 'dist/Gen_Bio_Atlas.html', html);
  }
  console.log('Built assets/data.js' + (process.argv.includes('--standalone') ? ' and dist/Gen_Bio_Atlas.html' : ''));
}
